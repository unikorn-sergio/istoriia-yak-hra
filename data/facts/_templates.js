/* Формулювання питань. РЕДАГУЄТЬСЯ РУКАМИ — єдиний файл у data/facts/, який
   не генерується. Решта файлів тут створює tools/facts-build.py.

   Ключ шукається в такому порядку:
     1. '<TYPE>|<predicate>'   — найточніше
     2. '<TYPE>'               — типовий для типу
     3. '_default'

   Підстановки: {concept}, {predicate}, {object}.

   ЧОМУ ТИРЕ, А НЕ ЗВИЧАЙНЕ РЕЧЕННЯ.
   Concept зберігається в називному відмінку. Українська вимагає знахідного
   («Хто очолював Українську Центральну Раду?»), а відмінювати рядок кодом
   надійно неможливо. Форма «{concept} — питання?» ставить концепт у називному
   перед тире й тому граматично правильна для БУДЬ-ЯКОГО концепту.
   Це свідомий обмін краси на те, щоб жодне питання не вийшло кривим. */

(function () {
  'use strict';

  window.FACTS_TEMPLATES = {

    /* --- точні формулювання під предикати ------------------------------- */

    'PERSON|очолював': '{concept} — хто очолював?',
    'PERSON|автор': '{concept} — хто автор?',
    'PERSON|засновник': '{concept} — хто засновник?',

    'DATE|дата': '{concept} — якого року?',
    'DATE|рік заснування': '{concept} — якого року засновано?',

    'PLACE|столиця': '{concept} — яке місто було столицею?',
    /* «де?», а не «де відбулося?»: предикат «місце» стосується і подій,
       і договорів, а «відбувся Берестейський мир» — кривий українською. */
    'PLACE|місце': '{concept} — де?',

    'DOCUMENT|зміст': '{concept} — що проголошував?',

    'ORGANIZATION|орган влади': '{concept} — який орган влади?',

    'CAUSE|причина': '{concept} — що стало причиною?',
    'CONSEQUENCE|наслідок': '{concept} — що стало наслідком?',

    'TERM|означення': '{concept} — що це означає?',

    /* --- типові для типу ------------------------------------------------ */

    'PERSON': '{concept} — хто?',
    'DATE': '{concept} — коли?',
    'PLACE': '{concept} — де?',
    'EVENT': '{concept} — що сталося?',
    'DOCUMENT': '{concept} — що це за документ?',
    'TERM': '{concept} — що це означає?',
    'ORGANIZATION': '{concept} — яка організація?',
    'CAUSE': '{concept} — що стало причиною?',
    'CONSEQUENCE': '{concept} — що стало наслідком?',
    'ATTRIBUTE': '{concept} — {predicate}?',
    'RELATION': '{concept} — {predicate}?',

    /* --- джерельні питання (факт має **Quote:**) --------------------------

       Формулювання НЕ називають концепт: інакше показаний уривок утрачає
       сенс, бо відповідь уже в питанні. Виняток — `_pick`, де концепт і є
       умовою, а варіантами виступають самі уривки. */

    'QUOTE|PERSON': 'Прочитайте уривок. Про кого йдеться?',
    'QUOTE|EVENT': 'Прочитайте уривок. Про яку подію йдеться?',
    'QUOTE|DATE': 'Прочитайте уривок. Якого року відбулися описані події?',
    'QUOTE|PLACE': 'Прочитайте уривок. Про яке місце йдеться?',
    'QUOTE|DOCUMENT': 'Прочитайте уривок. Про який документ ідеться?',
    'QUOTE|ORGANIZATION': 'Прочитайте уривок. Про яку організацію йдеться?',
    'QUOTE|CAUSE': 'Прочитайте уривок. Що стало причиною описаного?',
    'QUOTE|CONSEQUENCE': 'Прочитайте уривок. Що стало наслідком описаного?',
    'QUOTE|_pick': 'У якому уривку йдеться про: {concept}?',
    'QUOTE|_default': 'Прочитайте уривок. Про що йдеться?',

    /* --- останній відкат ------------------------------------------------ */

    '_default': '{concept} — {predicate}?'
  };
})();
